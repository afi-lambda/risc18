#: Core clock the harness is specified against (the PLL output of ``FullTop``).
CLK_HZ = 60_000_000

#: Line rate, the rate ``tools/hil_status.py`` opens the port at.
BAUD = 115_200


def baud_divisor(clk_hz=CLK_HZ, baud=BAUD):
    """Integer core clocks per UART bit: nearest divisor, never below 2."""
    return max(2, int(round(float(clk_hz) / float(baud))))


def baud_error(clk_hz=CLK_HZ, baud=BAUD):
    """``(actual_baud, relative_error)`` of the integer-divisor transmitter."""
    divisor = baud_divisor(clk_hz, baud)
    actual = float(clk_hz) / divisor
    return actual, (actual - float(baud)) / float(baud)


#: 521 at 60 MHz: 115 163.15 baud, -36.85 Hz, -320 ppm (see the module docstring).
UART_DIVISOR = baud_divisor()

#: The one line, as a Python format string.  :func:`format_line` is the only
#: producer and :func:`parse_line` the only consumer; both are pinned byte for
#: byte against the RTL by ``tests/test_hil.py``.
LINE_FORMAT = "OK retires=%04x cycles=%08x pc=%04x value=%05x\r\n"

#: ``(kind, payload)`` segments, in transmit order: a literal byte string or a
#: ``(field, width)`` pair rendered as ``width`` zero-padded lowercase hex digits.
LINE_SEGMENTS = (
    ("lit", b"OK retires="),
    ("field", "retires", 4),
    ("lit", b" cycles="),
    ("field", "cycles", 8),
    ("lit", b" pc="),
    ("field", "pc", 4),
    ("lit", b" value="),
    ("field", "value", 5),
    ("lit", b"\r\n"),
)


def _line_items():
    """Expand :data:`LINE_SEGMENTS` into one item per transmitted character.

    A literal segment contributes one ``("lit", byte)`` item per byte; a field
    contributes one ``("field", name, nibble)`` item per hex digit, most
    significant digit first.  This list *is* the RTL's character ROM and the
    reference for the tests, so the hardware and :func:`format_line` cannot
    drift apart without a test failing.
    """
    items = []
    for segment in LINE_SEGMENTS:
        if segment[0] == "lit":
            items.extend(("lit", byte) for byte in segment[1])
        else:
            _, name, width = segment
            items.extend(("field", name, width - 1 - digit)
                         for digit in range(width))
    return tuple(items)


LINE_ITEMS = _line_items()

#: Transmitted bytes per line (53 for the format above).
LINE_LEN = len(LINE_ITEMS)

#: Strict parser for the line.  The widths are part of the format, not a
#: convenience: a shorter or longer field is a different format and must fail.
LINE_RE = re.compile(
    r"OK retires=([0-9a-f]{4}) cycles=([0-9a-f]{8}) "
    r"pc=([0-9a-f]{4}) value=([0-9a-f]{5})\r\n"
)


def format_line(retires, cycles, pc, value):
    """Render the line exactly as the RTL transmits it (bytes, no newline added)."""
    return (LINE_FORMAT % (retires, cycles, pc, value)).encode("ascii")


def parse_line(raw):
    """Parse one line into ``{"retires", "cycles", "pc", "value"}`` ints.

    ``raw`` is bytes or str and must be exactly one line including ``\\r\\n``:
    a partial read, an extra trailing newline or a field of the wrong width
    raises :class:`ValueError` with the offending text, so a mis-parsed run can
    never be mistaken for a measurement.
    """
    text = raw.decode("ascii", "replace") if isinstance(raw, (bytes, bytearray)) else str(raw)
    match = LINE_RE.fullmatch(text)
    if match is None:
        raise ValueError(f"not a HIL status line: {text!r}")
    retires, cycles, pc, value = (int(group, 16) for group in match.groups())
    return {"retires": retires, "cycles": cycles, "pc": pc, "value": value}


# ---------------------------------------------------------------------------
# The clock: 25 MHz pad -> 60.000 MHz, the ``ecppll -i 25 -o 60`` instance.
# ---------------------------------------------------------------------------

#: Reference clock of the Colorlight 5A-75B (same oscillator ``risc18.pll`` uses).
F_IN_MHZ = 25.0

#: ``ecppll -i 25 -o 60``: PFD ``25/5 = 5 MHz``, VCO ``5 * 12 = 600 MHz``,
#: CLKOP ``600/10 = 60.000 MHz`` (0 Hz error, 0 ppm).
CLKI_DIV = 5
CLKFB_DIV = 12
CLKOP_DIV = 10

#: Static phase shift ecppll emits for ``CLKOP_DIV = 10`` (must be < CLKOP_DIV).
CLKOP_CPHASE = 4

#: CLKOP frequency of that set, MHz.
F_OUT_MHZ = F_IN_MHZ * CLKFB_DIV / CLKI_DIV


class HilPll(Elaboratable):
    """25 MHz -> 60.000 MHz ``EHXPLLL``, copied from ``ecppll -i 25 -o 60``.

    Why this class exists at all
    ----------------------------

    :class:`risc18.pll.Pll` divides twice: ``f_out = f_in * CLKFB_DIV /
    (CLKI_DIV * CLKOP_DIV)``.  With ``FEEDBK_PATH="CLKOP"`` -- the only feedback
    path either class uses -- that is not how the loop closes: CLKOP is fed
    back and divided by ``CLKFB_DIV`` down to the PFD, so the loop locks
    ``f_CLKOP = f_in * CLKFB_DIV / CLKI_DIV`` and the VCO runs at
    ``f_CLKOP * CLKOP_DIV``.  ``CLKOP_DIV`` therefore sets the VCO, not the
    output.  Two independent observations agree:

    * ``nextpnr-ecp5`` on the ``Pll()`` default set (1, 24, 10) prints
      ``Derived VCO frequency 6024.1 MHz ... out of legal range [400MHz,
      800MHz]`` and constrains the CLKOP net to 600.2 MHz -- i.e. 600 MHz out,
      6 GHz VCO, as the loop equation above says;
    * on the board, a heartbeat design clocked by ``Pll()`` produces no serial
      output at all, while the same design clocked by this class streams the
      message continuously (11.5 kB/s at 115 200 baud, measured).

    So a 60 MHz output from a 25 MHz reference needs ``CLKFB_DIV/CLKI_DIV =
    2.4 = 12/5``, which is what ``ecppll`` emits, along with
    ``CLKOP_CPHASE=4`` and ``CLKFB`` tied to the CLKOP net.  Changing only the
    dividers and keeping the rest of ``Pll()`` (``CLKOP_CPHASE=0``, ``CLKFB``
    tied low, ``ENCLKOP=1``) was *not* enough on this board -- the line came out
    stuck -- so the vendor's phase/feedback wiring is part of the recipe; the
    ``ICP_CURRENT``/``LPF_RESISTOR``/``MFG_*`` attributes turned out not to be
    (a build without them also streams).

    The 5 MHz PFD is below the 10 MHz floor :class:`risc18.pll.Pll` enforces,
    which is the other reason the correct set could not be expressed through
    that class; the board locks and runs with it, as measured.

    ``risc18.pll.Pll`` and every other top are left untouched: this class is how
    *this* harness gets its 60 MHz clock, and ``docs/metrics/hil5.md`` records
    the measurement that says so.
    """

    def __init__(self):
        self.clki_div = CLKI_DIV
        self.clkfb_div = CLKFB_DIV
        self.clkop_div = CLKOP_DIV
        #: 25 MHz reference from the board oscillator (CLKI).
        self.i_clk = Signal()
        #: CLKOP: 60.000 MHz, 50 % duty, no phase shift beyond ecppll's cphase.
        self.o_clk = Signal()
        #: LOCK: high once the loop has locked.
        self.o_locked = Signal()

    @property
    def f_pfd_mhz(self):
        """Phase-detector frequency, MHz (``f_in / CLKI_DIV``)."""
        return F_IN_MHZ / self.clki_div

    @property
    def f_vco_mhz(self):
        """VCO frequency, MHz (``f_out * CLKOP_DIV``)."""
        return self.f_out_mhz * self.clkop_div

    @property
    def f_out_mhz(self):
        """CLKOP frequency, MHz (``f_in * CLKFB_DIV / CLKI_DIV``)."""
        return F_IN_MHZ * self.clkfb_div / self.clki_div

    def elaborate(self, platform):
        m = Module()
        m.submodules.pll = Instance(
            "EHXPLLL",
            # ecppll -i 25 -o 60, verbatim (parameter and port names as yosys'
            # ecp5/cells_bb.v declares them).
            p_CLKI_DIV=self.clki_div,
            p_CLKFB_DIV=self.clkfb_div,
            p_CLKOP_DIV=self.clkop_div,
            p_CLKOP_CPHASE=CLKOP_CPHASE,
            p_CLKOP_FPHASE=0,
            p_CLKOP_ENABLE="ENABLED",
            p_CLKOS_ENABLE="DISABLED",
            p_CLKOS2_ENABLE="DISABLED",
            p_CLKOS3_ENABLE="DISABLED",
            p_CLKOS_DIV=8, p_CLKOS2_DIV=8, p_CLKOS3_DIV=8,
            p_CLKOS_CPHASE=0, p_CLKOS2_CPHASE=0, p_CLKOS3_CPHASE=0,
            p_CLKOS_FPHASE=0, p_CLKOS2_FPHASE=0, p_CLKOS3_FPHASE=0,
            p_FEEDBK_PATH="CLKOP",
            p_CLKOP_TRIM_POL="RISING", p_CLKOP_TRIM_DELAY=0,
            p_CLKOS_TRIM_POL="RISING", p_CLKOS_TRIM_DELAY=0,
            p_OUTDIVIDER_MUXA="DIVA", p_OUTDIVIDER_MUXB="DIVB",
            p_OUTDIVIDER_MUXC="DIVC", p_OUTDIVIDER_MUXD="DIVD",
            p_PLLRST_ENA="DISABLED", p_INTFB_WAKE="DISABLED",
            p_STDBY_ENABLE="DISABLED", p_DPHASE_SOURCE="DISABLED",
            p_INT_LOCK_STICKY="ENABLED", p_SYNC_ENABLE="DISABLED",
            p_REFIN_RESET="DISABLED",
            # Charge pump / loop filter settings from the ecppll header.
            a_ICP_CURRENT="12", a_LPF_RESISTOR="8",
            a_MFG_ENABLE_FILTEROPAMP="1", a_MFG_GMCREF_SEL="2",
            i_CLKI=self.i_clk,
            # ecppll ties CLKFB to the CLKOP net even with FEEDBK_PATH="CLKOP";
            # a build with CLKFB tied low and CPHASE=0 did not run here.
            i_CLKFB=self.o_clk,
            i_RST=0, i_STDBY=0,
            i_PHASESEL0=0, i_PHASESEL1=0, i_PHASEDIR=1, i_PHASESTEP=1,
            i_PHASELOADREG=1, i_PLLWAKESYNC=0,
            # ecppll ties ENCLKOP low; only CLKOP is used.
            i_ENCLKOP=0, i_ENCLKOS=0, i_ENCLKOS2=0, i_ENCLKOS3=0,
            o_CLKOP=self.o_clk, o_LOCK=self.o_locked,
            o_CLKOS=Signal(), o_CLKOS2=Signal(), o_CLKOS3=Signal(),
            o_INTLOCK=Signal(), o_REFCLK=Signal(), o_CLKINTFB=Signal(),
        )
        return m


class UartTx(Elaboratable):
    """8N1 UART transmitter at ``clk / divisor`` baud, no flow control.

    Frame: one low start bit, eight data bits least significant first, one high
    stop bit; the line idles high.  ``i_stb`` is sampled only while the
    transmitter is idle, ``o_busy`` is high for the whole frame, and each of the
    ten bit slots lasts exactly ``divisor`` clocks -- that exactness is what
    ``tests/test_hil.py`` pins at the bit centres.

    Power-up and reset: the register that drives the pad is *inverted*
    (``tx_low``: 1 means the line is driven low), so the FF's power-up value 0
    is already idle-high.  Trellis FFs power up at 0 and ``synth_ecp5`` runs
    without ``-dff`` here, so an ``init=1`` on the pad register would not reach
    the bitstream and the line would start with a spurious low (a false start
    bit) until the first clock; inverting removes that glitch by construction.
    Reset value 0 also means idle, so a reset mid-frame releases the line
    instead of leaving it low.

    ``domain`` selects the clock domain the transmitter runs in (the harness
    runs it in ``hil``; a standalone timing test can leave it at ``sync``).
    """

    def __init__(self, divisor=UART_DIVISOR, domain="sync"):
        self.divisor = int(divisor)
        if self.divisor < 2:
            raise ValueError(f"divisor must be >= 2, got {divisor!r}")
        self.domain = domain
        #: Byte to send; sampled on the clock edge that accepts ``i_stb``.
        self.i_data = Signal(8)
        #: One-cycle strobe, sampled only when the transmitter is idle.
        self.i_stb = Signal()
        #: Serial line: idle high, start bit low, LSB first.
        self.o_tx = Signal()
        #: High for the whole ten-bit frame, including the stop bit.
        self.o_busy = Signal()

    def elaborate(self, platform):
        m = Module()
        d = m.d[self.domain]

        tx_low = Signal()          # 1 = drive the line low (see the docstring)
        busy = Signal()
        shifter = Signal(10)       # bit 0 = the slot being driven right now
        slot = Signal(4)           # 0..9, index of that slot
        cnt = Signal(range(self.divisor))

        m.d.comb += [self.o_tx.eq(~tx_low), self.o_busy.eq(busy)]

        with m.If(~busy):
            with m.If(self.i_stb):
                d += [
                    busy.eq(1),
                    # start bit (0), data LSB first, stop bit (1)
                    shifter.eq(Cat(0, self.i_data, 1)),
                    slot.eq(0),
                    cnt.eq(0),
                    tx_low.eq(1),
                ]
        with m.Else():
            with m.If(cnt == self.divisor - 1):
                d += cnt.eq(0)
                with m.If(slot == 9):
                    # The stop bit has had its full slot: idle from here on.
                    d += [busy.eq(0), tx_low.eq(0)]
                with m.Else():
                    d += [shifter.eq(shifter >> 1), slot.eq(slot + 1),
                          tx_low.eq(~shifter[1])]
            with m.Else():
                d += cnt.eq(cnt + 1)

        return m


class HilStatus(Elaboratable):
    """Cycle/retire counters and the one-line status sequencer.

    Ports: the core's retire trace (``i_retire``, ``i_retire_pc``,
    ``i_retire_value``), ``i_halt``, and ``o_tx`` (the UART line).  The latched
    values stay visible as attributes (``cycles``, ``retires``, ``pc``,
    ``value``) and ``done`` goes high on the snapshot edge, which is what the
    simulation tests compare against and what the line is rendered from.

    Clocking: the harness owns a reset-bearing ``hil`` domain but does not
    drive it -- the top connects ``hil.cd.clk`` to the same 60 MHz net as the
    core and ``hil.cd.rst`` to the same ``BootReset`` output the core's reset
    comes from.  That shared reset is the whole reason the on-board counter and
    the simulated one agree: both start on the edge that lets the core run.

    Sequencing: wait for ``i_halt``; snapshot; render the 53 characters of
    :data:`LINE_FORMAT` one at a time through :class:`UartTx`, waiting for
    ``o_busy`` to rise (the byte was captured) and then to fall (the frame was
    sent) between characters; then park for good.  The counters are frozen on
    the snapshot edge, so what is transmitted cannot be affected by how long
    the line takes to clock out.  If a program never halts, ``BootReset``'s
    watchdog re-resets the core *and this harness* (same reset net), so a hung
    run silently restarts instead of emitting a stale line.
    """

    def __init__(self, *, divisor=UART_DIVISOR, cycles_bits=27, retires_bits=16,
                 domain="hil"):
        self.divisor = int(divisor)
        self.cycles_bits = int(cycles_bits)
        self.retires_bits = int(retires_bits)
        self.domain = domain
        if not 1 <= self.cycles_bits <= 32:
            raise ValueError(f"cycles_bits must be in 1..32, got {cycles_bits!r}")
        if not 1 <= self.retires_bits <= 32:
            raise ValueError(f"retires_bits must be in 1..32, got {retires_bits!r}")

        #: One pulse per instruction leaving W.
        self.i_retire = Signal()
        #: PC of that instruction (valid with ``i_retire``).
        self.i_retire_pc = Signal(16)
        #: Writeback/ALU value of that instruction (valid with ``i_retire``).
        self.i_retire_value = Signal(isa.WIDTH)
        #: The core's sticky halt flag (registered one cycle behind the retire).
        self.i_halt = Signal()

        #: The UART line.
        self.o_tx = Signal()
        #: High for the whole frame currently clocking out (debug/tests).
        self.o_busy = Signal()
        #: Set on the edge that snapshots the counters (once, for good).
        self.done = Signal()

        #: Core clock cycles through the cycle ``i_halt`` was first seen.
        self.cycles = Signal(cycles_bits)
        #: Retire pulses counted up to and including the HALT.
        self.retires = Signal(retires_bits)
        #: PC of the last retire.
        self.pc = Signal(16)
        #: Value of the last retire.
        self.value = Signal(isa.WIDTH)

        #: The transmitter, in the same domain as the counters.
        self.uart = UartTx(self.divisor, domain=domain)
        #: The domain the harness runs in; the top drives ``clk`` and ``rst``.
        self.cd = ClockDomain(domain)

    def elaborate(self, platform):
        m = Module()
        m.domains += self.cd
        d = m.d[self.domain]
        m.submodules.uart = uart = self.uart

        # ---- counters ------------------------------------------------------
        # ``cycles`` counts the cycle currently in progress: it reads 1 during
        # the first cycle after the reset is released and 26 during the cycle
        # the halt is first observed on the reference program.  Both counters
        # stop on the snapshot edge so the transmitted values are final.
        retires_next = self.retires + self.i_retire
        with m.If(~self.done):
            with m.If(self.i_halt):
                # The PC/value registers follow the pipeline every cycle, dead
                # slots included, so the "last retire" fields are latched from
                # the retire pulse itself and merely held on the halt edge.
                d += [
                    self.done.eq(1),
                    # A retire pulse in the same cycle as i_halt still counts.
                    self.retires.eq(retires_next),
                    self.pc.eq(Mux(self.i_retire, self.i_retire_pc, self.pc)),
                    self.value.eq(Mux(self.i_retire, self.i_retire_value,
                                      self.value)),
                ]
            with m.Else():
                d += [
                    self.cycles.eq(self.cycles + 1),
                    self.retires.eq(retires_next),
                ]
                with m.If(self.i_retire):
                    d += [self.pc.eq(self.i_retire_pc),
                          self.value.eq(self.i_retire_value)]

        # ---- character ROM -------------------------------------------------
        # One combinational byte per character index: literal bytes for the
        # fixed text, four nibbles per field for the numbers (lowercase, with
        # the zero padding the format promises).  A default keeps the mux total
        # (the project notes: never leave a switch without it).
        idx = Signal(range(LINE_LEN + 1))
        tx_byte = Signal(8)
        with m.Switch(idx):
            for position, item in enumerate(LINE_ITEMS):
                with m.Case(position):
                    if item[0] == "lit":
                        m.d.comb += tx_byte.eq(item[1])
                    else:
                        _, name, nibble = item
                        digit = (getattr(self, name) >> (4 * nibble)) & 0xF
                        m.d.comb += tx_byte.eq(
                            Mux(digit > 9, digit + (ord("a") - 10),
                                digit + ord("0")))
            with m.Default():
                m.d.comb += tx_byte.eq(ord(" "))

        # ---- sequencer -----------------------------------------------------
        # wait for the snapshot, then clock the line out one character at a
        # time.  LOAD asserts the strobe for exactly one cycle; HOLD waits for
        # the transmitter to claim it (that is the "wait for busy" step the
        # project notes ask for) and SEND waits for the frame to finish.
        with m.FSM(name="line", domain=self.domain):
            with m.State("WAIT"):
                with m.If(self.done):
                    d += idx.eq(0)
                    m.next = "LOAD"
            with m.State("LOAD"):
                m.d.comb += [uart.i_data.eq(tx_byte), uart.i_stb.eq(1)]
                m.next = "HOLD"
            with m.State("HOLD"):
                with m.If(uart.o_busy):
                    m.next = "SEND"
            with m.State("SEND"):
                with m.If(~uart.o_busy):
                    with m.If(idx == LINE_LEN - 1):
                        m.next = "STOP"
                    with m.Else():
                        d += idx.eq(idx + 1)
                        m.next = "LOAD"
            with m.State("STOP"):
                pass

        m.d.comb += self.o_busy.eq(uart.o_busy)
        m.d.comb += self.o_tx.eq(uart.o_tx)

        return m
