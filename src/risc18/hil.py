"""UART telemetry harness for the five-stage core (stage 3a HIL bring-up).

This module is the first serial port in the repository.  It turns the core's
retire trace into one fixed ASCII line on a 115 200 baud 8N1 line, so the same
numbers that ``amaranth.sim`` measures can be read back from the board and
compared field by field.

Line format -- exact, one line, then the harness goes quiet forever
-------------------------------------------------------------------

::

    OK retires=%04x cycles=%08x pc=%04x value=%05x\\r\\n

concretely, for the measurement the board actually produced::

    OK retires=000d cycles=0000001a pc=000f value=00000\\r\\n

* every numeric field is **lowercase hexadecimal, zero padded to a fixed
  width** (``retires`` 4, ``cycles`` 8, ``pc`` 4, ``value`` 5 digits), so the
  line has a constant 53 bytes and there is no ambiguity about how many digits
  a field has -- :func:`parse_line` matches the widths literally;
* fields are separated by exactly one space, the four field names are the ones
  above in that order, and the line ends with ``\\r\\n``;
* the numbers are in the order (retire count, core clock cycles, PC of the last
  retire, writeback/ALU value of the last retire).

Counters and the reset-to-halt convention
-----------------------------------------

Both counters live in the harness's own ``hil`` clock domain, which the top
clocks from the same PLL output as the core and resets from the same
``BootReset`` output the core's synchronous reset comes from.  The counters are
therefore held at 0 for exactly as long as the core is held in reset and start
counting on the clock edge that lets the core run:

* ``cycles`` -- number of core clock edges from the first edge after reset is
  released through the edge on which ``i_halt`` is first observed high,
  inclusive.  That is the reset-to-halt window, not the retire span: on
  ``CORE_TOP_PROGRAM`` the harness reports 26 cycles while the 13 retires span
  cycles 5..25 (21), which is the 1.615 CPI in ``docs/RESULTS.md``;
* ``retires`` -- the number of ``i_retire`` pulses, including the HALT's own
  pulse: the core registers ``o_halt`` one cycle behind the retire, so the
  snapshot is taken on ``i_halt`` and a retire pulse that coincides with it
  would still be counted (``retires + i_retire`` at the snapshot edge).

Baud rate: 60 000 000 / 115 200 = 520.8333.., so the divisor is either 520
(+184.6 Hz, +1602 ppm) or 521 (-36.9 Hz, -320 ppm).  521 is the nearest integer
and five times closer, so that is what :data:`UART_DIVISOR` is; a UART receiver
tolerates a couple of thousand ppm, so either would work, but 521 leaves the
whole tolerance budget to the FT2232H's own clock.

Nothing here is a memory: the line is generated by a small combinational
character ROM over a switch statement and clocked out one byte at a time,
waiting for the transmitter to go busy and then idle between bytes (the
handshake the project notes require for a UART).
"""

